from typing import Annotated, Any, List, Literal
from operator import add

from pydantic import BaseModel, Field


class AgentSchema(BaseModel):
    messages: List[Any] = Field(
        default_factory=list,
        description="Conversation messages (HumanMessage / AIMessage objects)",
    )
    user_question: str = Field(..., description="The original question by the user")
    curated_ques: str = Field(default="", description="Curated version of the user's question")
    prompt_query_context: str = Field(
        default="",
        description="Detailed prompt with SQL DB context used to generate the SQL query",
    )
    generated_sql_query: str = Field(default="", description="SQL query generated by the agent")
    is_safe: Literal["Yes", "No"] = Field(
        default="No", description="Whether the query is safe to execute"
    )
    comments: str = Field(default="", description="Judge's comments on the safety of the query")
    sql_query_execution_result: str = Field(
        default="", description="Result of executing the generated SQL query"
    )
    final_answer: str = Field(default="", description="Final response to the user")


class JudgeSchema(BaseModel):
    answer: Literal["Yes", "No"] = Field(..., description="Is the query safe to execute")
    comments: str = Field(..., description="Explanation of the decision")


class ETLAgentSchema(BaseModel):
    messages: Annotated[List,add] = Field(...,description="List of messages is proccessed by the ETL agent")


class RouterSchema(BaseModel):
    answer: Literal["etl", "sql"] = Field(
        description=(
            "Route the user's request. "
            "'etl' if they want to extract data from an API/file, transform it, or save/load it. "
            "'sql' if they ask a question that should be answered by querying the database."
        )
    )

class DataAgentSchema(BaseModel):
    messages : Annotated[list,add] = Field(..., description="List of messages to be processed by the Data agent")
    route_response : str = Field(..., description="The response from the router indicating whether to route to SQL or ETL operations")